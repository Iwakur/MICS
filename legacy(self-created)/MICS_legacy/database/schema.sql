CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    type account_type NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_accounts_code CHECK (char_length(code) > 0)
);

CREATE TABLE IF NOT EXISTS staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(100) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    family_name VARCHAR(100) NULL,
    father_name VARCHAR(100) NULL,
    status staff_status NOT NULL DEFAULT 'active',
    payout_card_number VARCHAR(64) NULL,
    fixed_salary_amount NUMERIC(10,2) NULL,
    profile_image_path VARCHAR(255) NULL,
    phone VARCHAR(32) NULL,
    email VARCHAR(255) NULL,
    comments TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_staff_fixed_salary_amount CHECK (fixed_salary_amount IS NULL OR fixed_salary_amount >= 0)
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id BIGINT NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    profile_image_path VARCHAR(255) NULL,
    role user_role NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_staff FOREIGN KEY (staff_id) REFERENCES staff(id)
);

CREATE TABLE IF NOT EXISTS plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    lesson_count NUMERIC(5,2) NOT NULL,
    lesson_price NUMERIC(10,2) NOT NULL,
    teacher_share_per_lesson NUMERIC(10,2) NOT NULL,
    is_assignable BOOLEAN NOT NULL DEFAULT TRUE,
    comments TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_plans_values CHECK (
        lesson_count >= 0 AND lesson_price >= 0 AND teacher_share_per_lesson >= 0
    )
);

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    family_name VARCHAR(100) NULL,
    father_name VARCHAR(100) NULL,
    profile_image_path VARCHAR(255) NULL,
    phone VARCHAR(32) NULL,
    email VARCHAR(255) NULL,
    status student_status NOT NULL DEFAULT 'active',
    plan_id BIGINT NOT NULL,
    staff_id BIGINT NOT NULL,
    discount_amount NUMERIC(10,2) NOT NULL DEFAULT 0,
    joined_at TIMESTAMPTZ NOT NULL,
    comments TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_students_plan FOREIGN KEY (plan_id) REFERENCES plans(id),
    CONSTRAINT fk_students_staff FOREIGN KEY (staff_id) REFERENCES staff(id),
    CONSTRAINT chk_students_discount CHECK (discount_amount >= 0)
);

CREATE TABLE IF NOT EXISTS student_charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    charge_month DATE NOT NULL,
    plan_id BIGINT NOT NULL,
    staff_id BIGINT NOT NULL,
    amount NUMERIC(10,2) NOT NULL,
    status document_status NOT NULL DEFAULT 'draft',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    posted_at TIMESTAMPTZ NULL,
    comment TEXT NULL,
    CONSTRAINT uq_student_charge_month UNIQUE (student_id, charge_month),
    CONSTRAINT fk_student_charges_student FOREIGN KEY (student_id) REFERENCES students(id),
    CONSTRAINT fk_student_charges_plan FOREIGN KEY (plan_id) REFERENCES plans(id),
    CONSTRAINT fk_student_charges_staff FOREIGN KEY (staff_id) REFERENCES staff(id),
    CONSTRAINT chk_student_charges_amount CHECK (amount > 0)
);

CREATE INDEX IF NOT EXISTS idx_student_charges_staff_month ON student_charges (staff_id, charge_month);

