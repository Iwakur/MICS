CREATE TABLE IF NOT EXISTS journal_entry_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_entry_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    debit_amount NUMERIC(10,2) NOT NULL DEFAULT 0,
    credit_amount NUMERIC(10,2) NOT NULL DEFAULT 0,
    student_id BIGINT NULL,
    staff_id BIGINT NULL,
    note TEXT NULL,
    CONSTRAINT fk_journal_lines_entry FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id),
    CONSTRAINT fk_journal_lines_account FOREIGN KEY (account_id) REFERENCES accounts(id),
    CONSTRAINT fk_journal_lines_student FOREIGN KEY (student_id) REFERENCES students(id),
    CONSTRAINT fk_journal_lines_staff FOREIGN KEY (staff_id) REFERENCES staff(id),
    CONSTRAINT chk_journal_line_nonnegative CHECK (debit_amount >= 0 AND credit_amount >= 0),
    CONSTRAINT chk_journal_line_one_side CHECK (
        (debit_amount > 0 AND credit_amount = 0) OR
        (debit_amount = 0 AND credit_amount > 0)
    )
);

CREATE INDEX IF NOT EXISTS idx_journal_lines_entry ON journal_entry_lines (journal_entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_account ON journal_entry_lines (account_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_student ON journal_entry_lines (student_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_staff ON journal_entry_lines (staff_id);

